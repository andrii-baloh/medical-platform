const fs = require('node:fs');
const html = fs.readFileSync('C:/Users/orest/Desktop/PAPA/MedicalPlatform/igor.html', 'utf8');
const checks = [];
const add = (name, ok, detail='') => checks.push({ name, ok, detail });
const count = (re) => (html.match(re) || []).length;
add('page is Norma landing', /<title>Норма/.test(html), 'title');
add('modal markup exists', html.includes('id="bookModal"'), '#bookModal');
add('booking buttons exist', count(/data-book=/g) > 0, String(count(/data-book=/g)));
add('base booking click handler exists', html.includes("const t = e.target.closest('[data-book]')") && html.includes('openModal(t.dataset.book'), 'openModal handler');
add('bad booking redirect removed', !html.includes('Route every visual CTA into the real application workflow') && !html.includes('location.href = slug ? `/book/'), 'no /doctors intercept');
add('CTA redirect removed', !html.includes('location.href = "/doctors";\n    }, true);'), 'no capture redirect');
add('doctor tab handler exists', html.includes("$$('.dtab').forEach") && html.includes("p.classList.toggle('on'"), 'dtab listener');
add('department accordion handler exists', html.includes("$$('.dept').forEach") && html.includes("body.classList.add('open')"), 'dept listener');
add('FAQ handler exists', html.includes("$$('.q-btn').forEach") && html.includes("q.classList.add('open')"), 'faq listener');
add('modal close handler exists', html.includes("e.target.closest('[data-close]')") && html.includes('closeModal()'), 'close listener');
add('phone mask exists', html.includes('function attachMask') && html.includes("attachMask($('#mTel'))"), 'phone mask');
add('booking form submit exists', html.includes("$('#bookForm').addEventListener('submit'") && html.includes('toast(`Вы записаны:'), 'book submit');
add('callback form submit exists', html.includes("$('#ctaForm').addEventListener('submit'") && html.includes('Координатор позвонит'), 'cta submit');
const hrefs = Array.from(html.matchAll(/<a\b[^>]*href=["']([^"']*)["']/g)).map(m => m[1]).filter(Boolean);
const badLinks = hrefs.filter(h => h === '#' || h.toLowerCase().startsWith('javascript:'));
add('no placeholder links', badLinks.length === 0, badLinks.join(', '));
const buttons = count(/<button\b/g);
add('buttons present', buttons > 0, String(buttons));
const bad = checks.filter(c => !c.ok);
console.log(JSON.stringify({ ok: bad.length === 0, checks, bad }, null, 2));
process.exit(bad.length ? 1 : 0);
